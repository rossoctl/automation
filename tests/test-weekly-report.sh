#!/usr/bin/env bash
set -euo pipefail

# Verifies scripts/weekly-report.sh builds the generator invocation from the
# RepoMan enrolled set. Hermetic: a fixture enrolled set via $REPOMAN_REPOS_FILE,
# a stub report.py via $REPORT_PY, and a failing gh so provenance falls back
# to blob/main without network. The enrolled set can span owners, so each repo
# is passed owner-qualified and there is no --org.

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
WRAPPER="$SCRIPT_DIR/../scripts/weekly-report.sh"

TEST_TMPDIR=$(mktemp -d)
trap 'rm -rf "$TEST_TMPDIR"' EXIT

fail=0

# Fixture enrolled set spanning two owners.
cat > "$TEST_TMPDIR/repos.json" <<'EOF'
[
  {"owner": "rossoctl", "name": "alpha"},
  {"owner": "alice", "name": "beta"}
]
EOF

# Stub generator: echo the args it was called with. With --output, also write a body.
cat > "$TEST_TMPDIR/report.py" <<'PY'
import sys
args = sys.argv[1:]
print(" ".join(args))
if "--output" in args:
    open(args[args.index("--output") + 1], "w").write("BODY\n")
PY

# Provenance must not call a real gh or write _meta into the scripts dir.
mkdir -p "$TEST_TMPDIR/bin" "$TEST_TMPDIR/meta"
cat > "$TEST_TMPDIR/bin/gh" << 'EOF'
#!/bin/sh
exit 1
EOF
chmod +x "$TEST_TMPDIR/bin/gh"
export PATH="$TEST_TMPDIR/bin:$PATH"
export REPOMAN_SKILL_DIR="$TEST_TMPDIR/meta"
FALLBACK='Generated by RepoMan github-weekly-report (https://github.com/rossoctl/agent-skills/blob/main/skills/github-weekly-report/SKILL.md).'

# Owner-qualified --repos, no --org. The footer is appended to the file, not stdout.
out="$TEST_TMPDIR/out.md"
got=$(REPOMAN_REPOS_FILE="$TEST_TMPDIR/repos.json" \
      REPORT_PY="$TEST_TMPDIR/report.py" \
      bash "$WRAPPER" --output "$out" 2>/dev/null)
want="--repos rossoctl/alpha alice/beta --output $out"
[ "$got" = "$want" ] || { echo "FAIL wrapper args: got [$got] want [$want]"; fail=1; }
[ "$(tail -n 1 "$out")" = "$FALLBACK" ] || { echo "FAIL output file missing footer: [$(tail -n 1 "$out")]"; fail=1; }
grep -q '^BODY$' "$out" || { echo "FAIL output file lost the report body"; fail=1; }

# --since / --until pass through. No --output, so the footer is the last stdout line.
got2=$(REPOMAN_REPOS_FILE="$TEST_TMPDIR/repos.json" \
       REPORT_PY="$TEST_TMPDIR/report.py" \
       bash "$WRAPPER" --since 2026-08-10 --until 2026-08-17 2>/dev/null)
want2="--repos rossoctl/alpha alice/beta --since 2026-08-10 --until 2026-08-17"
first2=$(printf '%s\n' "$got2" | head -n 1)
last2=$(printf '%s\n' "$got2" | tail -n 1)
[ "$first2" = "$want2" ] || { echo "FAIL wrapper window args: got [$first2] want [$want2]"; fail=1; }
[ "$last2" = "$FALLBACK" ] || { echo "FAIL stdout missing footer: [$last2]"; fail=1; }

# Missing generator fails loud.
if REPOMAN_REPOS_FILE="$TEST_TMPDIR/repos.json" \
   REPORT_PY="$TEST_TMPDIR/does-not-exist.py" \
   bash "$WRAPPER" >/dev/null 2>&1; then
  echo "FAIL wrapper should error on missing REPORT_PY"; fail=1
fi

# Empty enrolled set fails loud (never produces a zero-repo report).
echo '[]' > "$TEST_TMPDIR/empty.json"
if REPOMAN_REPOS_FILE="$TEST_TMPDIR/empty.json" \
   REPORT_PY="$TEST_TMPDIR/report.py" \
   bash "$WRAPPER" >/dev/null 2>&1; then
  echo "FAIL wrapper should error on empty enrolled set"; fail=1
fi

if [ "$fail" -eq 0 ]; then echo "PASS test-weekly-report.sh"; fi
exit "$fail"
